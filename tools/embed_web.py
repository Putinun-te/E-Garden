#!/usr/bin/env python3
"""Gzip firmware/hub/web/index.html into firmware/hub/web_index.h.

The page is compiled into the hub firmware, so it is always available, even
if the filesystem is damaged, and no separate filesystem upload is needed.
Run after editing index.html:  python3 tools/embed_web.py
CI runs it with --check and fails if web_index.h is out of date.
"""
import gzip
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "firmware/hub/web/index.html"
OUT = ROOT / "firmware/hub/web_index.h"


def render() -> str:
    data = gzip.compress(SRC.read_bytes(), compresslevel=9, mtime=0)
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    body = ",\n  ".join(rows)
    return (
        "// Generated by tools/embed_web.py from web/index.html. Do not edit by hand.\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        f"const size_t WEB_INDEX_GZ_LEN = {len(data)};\n"
        f"const uint8_t WEB_INDEX_GZ[] PROGMEM = {{\n  {body}\n}};\n"
    )


def embedded_page() -> bytes:
    import re
    data = bytes(int(h, 16) for h in re.findall(r"0x([0-9a-f]{2})", OUT.read_text().split("PROGMEM", 1)[1]))
    return gzip.decompress(data)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        # Compare the decompressed bytes: gzip output can differ between zlib
        # versions (macOS vs Linux) even for identical input.
        if not OUT.exists() or embedded_page() != SRC.read_bytes():
            print("web_index.h is out of date: run python3 tools/embed_web.py", file=sys.stderr)
            return 1
        print("web_index.h is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({SRC.stat().st_size} bytes -> {text.count('0x')} gzipped)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
